def canonicalize_header(name: str) -> str:
    raw = (name or "").strip()
    if not raw:
        return raw
    if raw in CANONICAL_FIELDS:
        return raw
    key = raw.lower().replace("ё", "е")
    key = key.replace(" ", "_")
    # also try with spaces as in aliases
    key2 = raw.lower().replace("ё", "е")
    if key in HEADER_ALIASES:
        return HEADER_ALIASES[key]
    if key2 in HEADER_ALIASES:
        return HEADER_ALIASES[key2]
    # soft: underscores
    k3 = key2.replace(" ", "_")
    if k3 in HEADER_ALIASES:
        return HEADER_ALIASES[k3]
    return raw


def normalize_row(row: dict[str, str]) -> dict[str, str]:
    out: dict[str, str] = {}
    for k, v in row.items():
        if k is None:
            continue
        ck = canonicalize_header(str(k))
        if ck in out and (out[ck] or "").strip() and not (str(v or "").strip()):
            continue
        out[ck] = "" if v is None else str(v)
    return out


def mapping_table_markdown() -> str:
    lines = [
        "| Канон (CSV / форма MPP) | Внутреннее поле Project |",
        "|-------------------------|-------------------------|",
    ]
    for internal, canon in MPP_INTERNAL_TO_CANON.items():
        lines.append(f"| {canon} | {internal} |")
    return "\n".join(lines)
